-- Schéma e-commerce : clients, produits, commandes, lignes de commande
-- + commentaires sur les produits, gérés par l'application catalogue (partie PHP)
-- Cible : PostgreSQL 12+
--
-- Le catalogue est celui de fakestoreapi.com : la table `product` en est la copie
-- locale (alimentée par la commande `bin/console app:import-products`).
-- Un produit a son propre id (celui de l'application) et, s'il provient d'une source
-- externe, le nom de cette source et l'id du produit chez ce fournisseur.
--
-- Toutes les tables ont deux colonnes techniques gérées par la base, jamais par l'application :
--   created_at : date de création de la ligne (DEFAULT CURRENT_TIMESTAMP)
--   updated_at : date de dernière modification (trigger set_updated_at), égale
--                à created_at tant que la ligne n'a pas été modifiée
--
-- Le script s'exécute dans la base courante (psql -d blissim) : il ne crée pas la base.
-- Rejouer ce script réinitialise entièrement les tables, commentaires compris.
-- =============================================================================

SET client_encoding = 'UTF8';

DROP TABLE IF EXISTS comment, order_item, customer_order, product, customer;

-- -----------------------------------------------------------------------------
-- updated_at : PostgreSQL n'a pas d'équivalent à ON UPDATE CURRENT_TIMESTAMP.
-- Ce trigger met la date à jour seulement si une valeur de la ligne change (un
-- upsert avec des données identiques ne la modifie pas), sauf si la requête
-- fournit elle-même une nouvelle valeur de updated_at.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$
BEGIN
    IF NEW IS DISTINCT FROM OLD AND NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at THEN
        NEW.updated_at := CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- -----------------------------------------------------------------------------
-- Clients
-- -----------------------------------------------------------------------------
CREATE TABLE customer (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    first_name  VARCHAR(100) NOT NULL,
    last_name   VARCHAR(100) NOT NULL,
    email       VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_customer_email UNIQUE (email)
);

CREATE TRIGGER trg_customer_updated_at BEFORE UPDATE ON customer
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- Produits (copie locale du catalogue FakeStore)
-- id                  : identifiant de l'application, référencé par les clés étrangères.
-- source              : origine du produit ('fakestore'), NULL pour un produit créé dans l'application.
-- supplier_product_id : identifiant du produit chez la source. VARCHAR, car une autre
--                       source peut utiliser un SKU ou un UUID. Unique par source : c'est
--                       la clé de l'upsert à l'import. Renseigné si et seulement si source l'est.
-- Les montants sont stockés en centimes (entiers) : calculs exacts, sans erreur
-- d'arrondi, et un type simple à manipuler côté PHP (int). 109,95 € => 10995.
-- `price_cents` est le prix catalogue courant : il peut changer à chaque import,
-- c'est pour ça qu'il est recopié dans order_item au moment de l'achat.
-- -----------------------------------------------------------------------------
CREATE TABLE product (
    id                   INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    source               VARCHAR(50)   NULL,
    supplier_product_id  VARCHAR(64)   NULL,
    name                 VARCHAR(255)  NOT NULL,
    description          TEXT          NULL,
    category             VARCHAR(100)  NOT NULL DEFAULT '',
    image_url            VARCHAR(500)  NOT NULL,
    price_cents          INTEGER       NOT NULL,
    created_at           TIMESTAMP(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMP(0)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT uq_product_supplier UNIQUE (source, supplier_product_id),
    CONSTRAINT chk_product_supplier CHECK ((source IS NULL) = (supplier_product_id IS NULL)),
    CONSTRAINT chk_product_price CHECK (price_cents >= 0)
);

CREATE INDEX idx_product_category ON product (category);

CREATE TRIGGER trg_product_updated_at BEFORE UPDATE ON product
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- Commandes
-- Table nommée customer_order car ORDER est un mot réservé SQL.
-- ON DELETE RESTRICT : on ne supprime pas un client qui a un historique d'achat.
-- ordered_at est la date métier de la commande (celle des requêtes), distincte de
-- created_at, date technique d'insertion de la ligne (ex. commande importée plus tard).
-- -----------------------------------------------------------------------------
CREATE TABLE customer_order (
    id           INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    customer_id  INTEGER      NOT NULL,
    status       VARCHAR(20)  NOT NULL DEFAULT 'pending',
    ordered_at   TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at   TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_order_customer FOREIGN KEY (customer_id)
        REFERENCES customer (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_order_status CHECK (status IN ('pending', 'paid', 'shipped', 'cancelled'))
);

-- PostgreSQL n'indexe pas automatiquement les clés étrangères
CREATE INDEX idx_order_customer ON customer_order (customer_id);

-- Sert la requête 2 (ventes des 7 derniers jours)
CREATE INDEX idx_order_ordered_at ON customer_order (ordered_at);

CREATE TRIGGER trg_customer_order_updated_at BEFORE UPDATE ON customer_order
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- -----------------------------------------------------------------------------
-- Lignes de commande
-- unit_price_cents = prix payé au moment de l'achat, en centimes
-- (figé, indépendant de product.price_cents).
-- Un même produit n'apparaît qu'une fois par commande (on cumule la quantité).
-- -----------------------------------------------------------------------------
CREATE TABLE order_item (
    id                INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    order_id          INTEGER      NOT NULL,
    product_id        INTEGER      NOT NULL,
    quantity          SMALLINT     NOT NULL,
    unit_price_cents  INTEGER      NOT NULL,
    created_at        TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at        TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_item_order FOREIGN KEY (order_id)
        REFERENCES customer_order (id) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_item_product FOREIGN KEY (product_id)
        REFERENCES product (id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_item_order_product UNIQUE (order_id, product_id),
    CONSTRAINT chk_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_item_price CHECK (unit_price_cents >= 0)
);

-- order_id est déjà couvert par uq_item_order_product (première colonne)
CREATE INDEX idx_item_product ON order_item (product_id);

CREATE TRIGGER trg_order_item_updated_at BEFORE UPDATE ON order_item
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


-- -----------------------------------------------------------------------------
-- Commentaires sur les produits (application catalogue)
-- ON DELETE CASCADE : un commentaire n'a pas de sens sans son produit.
-- -----------------------------------------------------------------------------
CREATE TABLE comment (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    product_id  INTEGER      NOT NULL,
    author      VARCHAR(100) NOT NULL,
    content     TEXT         NOT NULL,
    created_at  TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMP(0) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_comment_product FOREIGN KEY (product_id)
        REFERENCES product (id) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE INDEX idx_comment_product ON comment (product_id);

CREATE TRIGGER trg_comment_updated_at BEFORE UPDATE ON comment
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


