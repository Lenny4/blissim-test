-- 1. Prénom et nom des clients ayant commandé le produit product_id = 1.
--    DISTINCT : un client qui a commandé le produit plusieurs fois n'apparaît qu'une fois.
--    Résultat attendu sur le seed : Camille Martin, Lucas Bernard, Chloé Robert, Nathan Petit.
--    (On ne filtre pas sur le statut : la question porte sur "avoir commandé".)
SELECT DISTINCT c.first_name, c.last_name
FROM customer c
JOIN customer_order o ON o.customer_id = c.id
JOIN order_item oi    ON oi.order_id   = o.id
WHERE oi.product_id = 1
ORDER BY c.last_name, c.first_name;

-- 2. Produits vendus au cours des 7 derniers jours, avec leur nom et la quantité
--    totale vendue, triés par quantité décroissante.
--    Les commandes annulées ne sont pas des ventes : elles sont exclues.
--    La condition sur ordered_at est "sargable" et profite de idx_order_ordered_at.
--    Résultat attendu sur le seed :
--      Mens Casual Slim Fit 4 / Fjallraven Backpack 3 / Mens Cotton Jacket 3 /
--      John Hardy Bracelet 1 / Mens Casual Premium T-Shirts 1
SELECT p.id, p.name, SUM(oi.quantity) AS total_quantity
FROM order_item oi
JOIN customer_order o ON o.id = oi.order_id
JOIN product p        ON p.id = oi.product_id
WHERE o.ordered_at >= NOW() - INTERVAL '7 days'
  AND o.status <> 'cancelled'
GROUP BY p.id, p.name
ORDER BY total_quantity DESC, p.name;
